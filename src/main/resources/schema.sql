-- CineBook schema. Runs on every startup; IF NOT EXISTS keeps existing data.
CREATE TABLE IF NOT EXISTS MOVIE (
    movie_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(100)  NOT NULL,
    genre        VARCHAR(50)   NOT NULL,
    ticket_price DECIMAL(7, 2) NOT NULL,
    CONSTRAINT chk_movie_title_not_blank CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT chk_movie_genre_not_blank CHECK (LENGTH(TRIM(genre)) > 0),
    CONSTRAINT chk_movie_ticket_price    CHECK (ticket_price > 0 AND ticket_price <= 10000)
);
